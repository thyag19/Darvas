"""Synthetic demonstration data. Every name, number and date here is invented by this module: it carries no third-party
rights, which is the only reason the DEMO sources may be recorded as display-cleared. It exists so the dashboard and
the end-to-end tests can run without any restricted data. It must never be presented as real market data.
"""
from __future__ import annotations

import datetime as dt
import math
from pathlib import Path
from typing import Dict

from .sources import Access, SourceSpec, validate
from .models import SourceGrade

DEMO_NOW = dt.datetime(2026, 10, 22, 10, 0, tzinfo=dt.timezone.utc)   # 15:30 IST
LAST_TRADE = dt.date(2026, 10, 21)


def demo_registry() -> Dict[str, SourceSpec]:
    ev = "Synthetic data generated by irie.demo; no third-party rights involved."
    common = dict(kind="file_inbox", access=Access.USER_SUPPLIED, synthetic=True, terms_checked_on=dt.date(2026, 10, 22),
                  display_cleared=True, display_evidence=ev, min_interval_s=0,
                  provides=("instruments", "distributions", "prices", "navs", "leverage", "news", "holdings"))
    reg = {"DEMO": SourceSpec("DEMO", "Synthetic demo data (issuer grade)", SourceGrade.ISSUER, **common),
           "DEMO2": SourceSpec("DEMO2", "Synthetic demo data (aggregator grade)", SourceGrade.AGGREGATOR, **common)}
    validate(reg)
    return reg


def _hdr(*c):
    return ",".join(c) + "\n"


def write_demo_inbox(root) -> None:
    root = Path(root)
    (root / "DEMO").mkdir(parents=True, exist_ok=True)
    (root / "DEMO2").mkdir(parents=True, exist_ok=True)
    inst = _hdr("key", "name", "type", "etf_category", "distributes", "isin")
    inst += ("DEMO_INVIT_A,DEMO InvIT Alpha (synthetic),INVIT,,,\n"
             "DEMO_INVIT_B,DEMO InvIT Beta (synthetic),INVIT,,,\n"
             "DEMO_INVIT_C,DEMO InvIT Gamma (synthetic),INVIT,,,\n"
             "DEMO_REIT_A,DEMO REIT Alpha (synthetic),REIT,,,\n"
             "DEMO_ETF_EQ,DEMO Equity Index ETF (synthetic),ETF,EQUITY_BROAD,N,\n"
             "DEMO_ETF_GOLD,DEMO Gold ETF (synthetic),ETF,GOLD_SILVER,N,\n"
             "DEMO_ETF_DEBT,DEMO Debt ETF (synthetic),ETF,DEBT,Y,\n")
    (root / "DEMO" / "instruments_demo.csv").write_text(inst)

    dh = _hdr("instrument_key", "ex_date", "record_date", "total_per_unit", "interest", "dividend", "rental",
              "other_income", "capital_repayment", "include", "amount_grade", "source_id")
    quarters = [dt.date(2024, 11, 14), dt.date(2025, 2, 13), dt.date(2025, 5, 15), dt.date(2025, 8, 14),
                dt.date(2025, 11, 13), dt.date(2026, 2, 12), dt.date(2026, 5, 14), dt.date(2026, 8, 13)]
    for i, q in enumerate(quarters):
        a_total = 2.40 + 0.05 * i
        cap = round(0.60 - 0.02 * i, 4)
        interest = round(a_total - cap - 0.10, 4)
        dh += f"DEMO_INVIT_A,{q},{q},{a_total:.4f},{interest},0.1000,,,{cap},Y,ISSUER,DEMO\n"
        dh += f"DEMO_INVIT_B,{q},{q},{2.00 + 0.02 * i:.4f},,,,,,Y,ISSUER,DEMO\n"
        dh += f"DEMO_INVIT_C,{q},{q},{3.10:.4f},,,,,,Y,AGGREGATOR,DEMO\n"
        r_total = 1.80 + 0.03 * i
        dh += f"DEMO_REIT_A,{q},{q},{r_total:.4f},0.2000,0.1000,{r_total - 0.35:.4f},,0.0500,Y,ISSUER,DEMO\n"
    for q in (dt.date(2025, 12, 20), dt.date(2026, 6, 20)):
        dh += f"DEMO_ETF_DEBT,{q},{q},0.8000,,,,,,Y,ISSUER,DEMO\n"
    (root / "DEMO" / "distributions_demo.csv").write_text(dh)

    px = _hdr("instrument_key", "date", "price", "venue")
    nv = _hdr("instrument_key", "nav_date", "nav", "kind", "grade")
    base = {"DEMO_INVIT_A": 100.0, "DEMO_INVIT_B": 95.0, "DEMO_INVIT_C": 110.0, "DEMO_REIT_A": 310.0,
            "DEMO_ETF_EQ": 250.0, "DEMO_ETF_GOLD": 60.0, "DEMO_ETF_DEBT": 1100.0}
    start = LAST_TRADE - dt.timedelta(weeks=70)
    for k, b in base.items():
        drift = 0.0006 + 0.0004 * list(base).index(k)
        for w in range(70):
            d = start + dt.timedelta(weeks=w)
            val = b * (1 + 0.04 * math.sin(w / 6.0 + list(base).index(k)) + drift * w)
            px += f"{k},{d},{val:.2f},NSE\n"
            if k.startswith("DEMO_ETF"):
                nv += f"{k},{d},{val * 1.001:.4f},FUND_NAV,ISSUER\n"
        px += f"{k},{LAST_TRADE},{b * 1.02:.2f},NSE\n"
        if k.startswith("DEMO_ETF"):
            nv += f"{k},{LAST_TRADE},{b * 1.02 * 1.001:.4f},FUND_NAV,ISSUER\n"
    for k, n in (("DEMO_INVIT_A", 105.0), ("DEMO_INVIT_B", 98.0), ("DEMO_INVIT_C", 112.0), ("DEMO_REIT_A", 285.0)):
        nv += f"{k},2026-06-30,{n:.2f},FAIR_VALUE,ISSUER\n"
    (root / "DEMO" / "prices_demo.csv").write_text(px)
    (root / "DEMO" / "navs_demo.csv").write_text(nv)
    (root / "DEMO" / "leverage_demo.csv").write_text(
        _hdr("instrument_key", "date", "value", "definition", "grade") +
        "DEMO_INVIT_A,2026-06-30,0.45,SEBI_NET_BORROWINGS_RATIO,ISSUER\n"
        "DEMO_REIT_A,2026-06-30,0.31,NET_DEBT_TO_GAV,ISSUER\n")
    write_demo_news_and_holdings(root)
    # second, lower-grade source disagreeing on one REIT price: exercises discrepancy handling
    (root / "DEMO2" / "prices_demo2.csv").write_text(
        _hdr("instrument_key", "date", "price", "venue") + f"DEMO_REIT_A,{LAST_TRADE},{310.0 * 1.02 + 6:.2f},NSE\n")


def write_demo_news_and_holdings(root) -> None:
    """Synthetic announcements and ETF portfolios. Headlines are invented, link to a reserved .invalid host, and are
    labelled SYNTHETIC in the UI. They describe nothing that happened."""
    root = Path(root)
    base = DEMO_NOW
    items = [
        (25, "REIT", "DEMO_REIT_A", "SYNTHETIC EXAMPLE: DEMO REIT Alpha announces a distribution for the quarter",
         "Invented announcement used to exercise the news panel. No real REIT is described."),
        (70, "INFRASTRUCTURE", "DEMO_INVIT_A", "SYNTHETIC EXAMPLE: DEMO InvIT Alpha reports a toll-road traffic update",
         "Invented item. The figures in it do not exist."),
        (130, "CORPORATE", "DEMO_INVIT_B", "SYNTHETIC EXAMPLE: DEMO InvIT Beta schedules a board meeting",
         "Invented corporate-announcement example."),
        (300, "INVIT", "DEMO_INVIT_C", "SYNTHETIC EXAMPLE: DEMO InvIT Gamma publishes valuation summary",
         "Invented item for the InvIT filter."),
        (900, "REIT", "", "SYNTHETIC EXAMPLE: Sector note on office leasing (no instrument)",
         "Invented item without an instrument link."),
        (1500, "CORPORATE", "DEMO_ETF_EQ", "SYNTHETIC EXAMPLE: DEMO Equity Index ETF notice to unitholders",
         "Invented corporate-announcement example for an ETF."),
        (2900, "INFRASTRUCTURE", "", "SYNTHETIC EXAMPLE: Regulator circular example (invented)",
         "Invented item; no regulator published it."),
    ]
    lines = _hdr("published_at", "publisher", "category", "instrument_key", "headline", "summary", "url")
    for i, (mins, cat, key, head, summ) in enumerate(items, 1):
        t = (base - dt.timedelta(minutes=mins)).strftime("%Y-%m-%dT%H:%M:%SZ")
        lines += f'{t},Synthetic wire,{cat},{key},"{head}","{summ}",https://example.invalid/demo/news-{i}\n'
    (root / "DEMO" / "news_demo.csv").write_text(lines)
    h = _hdr("instrument_key", "as_of", "isin", "name", "weight_pct")
    weights = [9.0, 8.0, 7.0, 6.5, 6.0, 5.5, 5.0, 4.5, 4.0, 3.5, 3.0, 2.5, 35.0]     # 13 names summing to 100
    for k, d in (("DEMO_ETF_EQ", "2026-09-30"), ("DEMO_ETF_DEBT", "2026-07-31")):
        for n, w in enumerate(weights, 1):
            h += f"{k},{d},SYN{n:09d},DEMO Holding {n:02d} (synthetic),{w}\n"
    (root / "DEMO" / "holdings_demo.csv").write_text(h)
